from gsmap.project import Project  # noqa: E402
from gsmap.scenes import Scenes  # noqa: E402

HUB_SCENE, HUB_MAP, HUB_ROW, HUB_OVERLAY = 191, "172", 178, 0x3CC
# The sandbox: the second Djinn test room (scene 192, map 173, layered row 179),
# given Vale's tile set and an open field to paint on.
SANDBOX_SCENE, SANDBOX_MAP, SANDBOX_ROW, SANDBOX_ART = 192, "173", 179, "002"
SANDBOX_CODE, SANDBOX_RETURN_CODE = 190, 200  # hub pad / sandbox's way back
ART_MAP = "009"  # Sol Sanctum: the hub borrows its tile set
SKIP = {0, 1} | set(range(191, 201))  # title, file select, debug rooms
EVENT_EXIT_CONTROL = 0x1  # EVENT_EXIT, as 886 of the game's exit events
SEARCH_MESSAGE_CONTROL = 0xF3  # the game's usual search-with-message control
FIND_MESSAGE = 0x00400000
PO_BEGIN = "# gsmod: debug hub messages BEGIN (generated by gs-mapedit tools/debug_hub.py)"
PO_END = "# gsmod: debug hub messages END"
LINE_WIDTH, LINES_PER_BOX = 20, 3


def box_text(pad, label):
    """'Pad 72: warp to Xian - Xian Houses' wrapped for a dialogue box."""
    prefix = "Back to" if pad == SANDBOX_RETURN_CODE else f"Pad {pad}: warp to"
    text = f"{prefix} " + label.replace(" · ", " - ")
    text = text.replace("\u2019", "'").encode("ascii", "ignore").decode()
    lines, cur = [], ""
    for word in text.split():
        if cur and len(cur) + 1 + len(word) > LINE_WIDTH:
            lines.append(cur)
            cur = word
        else:
            cur = f"{cur} {word}".strip()
    lines.append(cur)
    out = ""
    for i, line in enumerate(lines):
        if i:
            out += "{page_break}" if i % LINES_PER_BOX == 0 else "\\n"
        out += line.replace('"', '\\"')
    return out + "{end_wait}"


def write_messages(po_path, dests):
    """Append one message per pad to the English catalog (replacing an earlier
    generated block) and return their message numbers."""
    text = open(po_path, encoding="utf-8").read()
    if PO_BEGIN in text:
        text = text[: text.index(PO_BEGIN)].rstrip("\n") + "\n"
    import re
    base = max(int(m) for m in re.findall(r'^msgid "(\d{5})"', text, re.M)) + 1
    block = ["", PO_BEGIN]
    for i, d in enumerate(dests):
        block += ["", 'msgctxt "message"', f'msgid "{base + i:05d}"', f'msgstr "{box_text(d["code"], d["label"])}"']
    block += ["", PO_END, ""]
    with open(po_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text + "\n".join(block))
    return [base + i for i in range(len(dests))]


SANDBOX_TILESET_DIR = "graphics/tileset/set_sandbox"
SANDBOX_TILESET_LABELS = ["Tileset_SandboxPalette", "Tileset_SandboxTilesA",
                          "Tileset_SandboxTilesB", "Tileset_SandboxTilesC", "Tileset_SandboxTilesD"]


def install_sandbox_tileset(project, art, map_s):
    """Copy the art map's tile set into set_sandbox (once: it then holds the
    player's custom tiles), define its labels in the sandbox's map.s and
    register them in five of the resource directory's unused slots."""
    dst = os.path.join(project.tbs, SANDBOX_TILESET_DIR)
    if not os.path.isdir(dst):
        os.makedirs(dst)
        res = art.resources
        sources = [project.label_path(res["palette"])] + [project.label_path(b) for b in res["blocks"]] \
            + [project.label_path(res["sheet_d"])]
        for name, srcp in zip(["palette.png", "tiles_a.png", "tiles_b.png", "tiles_c.png", "tiles_d.png"], sources):
            shutil.copy(srcp, os.path.join(dst, name))
    text = open(map_s, encoding="utf-8").read()
    if "Tileset_SandboxPalette:" not in text:
        rel = "games/tbs/src/" + SANDBOX_TILESET_DIR
        forms = ["palette.gbapal.lz", "tiles_a.4bpp.mtf", "tiles_b.4bpp.mtf", "tiles_c.4bpp.mtf", "tiles_d.4bpp.mtf"]
        block = ["", "@ gs-mapedit: the debug sandbox's own tile set (a copy of Vale's, plus custom tiles)"]
        for label, form in zip(SANDBOX_TILESET_LABELS, forms):
            block += [f"\t.global {label}", "\t.balign 4, 0", f"{label}:", f'\t.incbin "{rel}/{form}"']
        with open(map_s, "w", encoding="utf-8", newline="\n") as f:
            f.write(text.rstrip("\n") + "\n" + "\n".join(block) + "\n")
    dpath = os.path.join(project.tbs, "system/resource/directory.s")
    text = open(dpath, encoding="utf-8").read()
    if "Tileset_SandboxPalette" not in text:
        new = "\t@ gs-mapedit: the debug sandbox's tile set\n" + "".join(
            f"\tresource , {label}\n" for label in SANDBOX_TILESET_LABELS) + "\tunused 20\n"
        assert text.count("\tunused 25\n") == 1, "directory's spare slots changed"
        text = text.replace("\tunused 25\n", new)
        with open(dpath, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


def make_sandbox(project, root):
    """Scene 192's room as an open field in Vale's tile set: its own map
    files, Vale's resources, three layers, grass inside a wall, and a way
    back to the hub next to where the party arrives."""
    sb = project.maps[SANDBOX_MAP]
    folder = sb.folder
    # First run only: later runs keep the player's edits and custom blocks.
    fresh = not os.path.exists(os.path.join(folder, "grid_metatile.tsv"))
    src = os.path.join(project.tbs, "map/map_001")
    for name in ("grid.tsv", "grid_collision.tsv", "grid_metatile.tsv", "grid_shape.tsv", "shapes.tsv"):
        if not os.path.exists(os.path.join(folder, name)):
            shutil.copy(os.path.join(src, name), folder)
    art = project.maps[SANDBOX_ART]
    # map.s: own blocks, Vale's priorities and char bases, three layer windows
    ms = os.path.join(folder, "map.s")
    text = open(ms, encoding="utf-8").read()
    text = text.replace("games/tbs/src/map/map_001/", "games/tbs/src/map/map_173/")
    text = re.sub(r"map_header 0, 0, 64, 64, [^\n]*", "map_header 0, 0, 64, 64, "
                  + ", ".join(str(v) for v in art.priority + art.char_base) + ", 0, 0", text, count=1)
    layers = iter(["map_layer 0, 0, 16, 16, 0, 0, 0xff, 0xff",
                   "map_layer 64, 0, 16, 16, 0, 0, 0xff, 0xff",
                   "map_layer 128, 0, 16, 16, 0, 0, 0xff, 0xff"])
    head, sep, tail = text.partition(".LField_Map173_METATILES:")
    head = re.sub(r"map_layer [^\n]*", lambda m: next(layers), head)
    with open(ms, "w", encoding="utf-8", newline="\n") as f:
        f.write(head + sep + tail)
    # tile set: the sandbox's own copy of Vale's (so custom art never touches
    # Vale), registered in five of the directory's spare slots
    install_sandbox_tileset(project, art, ms)
    entries = Project(root).directory_entries()
    base = entries.index("Field_Map001")
    lpath = os.path.join(project.tbs, "field/layered.tsv")
    lt = tablemod.load(lpath)
    for c, label in enumerate(SANDBOX_TILESET_LABELS, start=1):
        lt.set(SANDBOX_ROW, c, entries.index(label) - base)
    tablemod.save(lt, lpath)
    if not fresh:
        print("sandbox: kept as edited (delete map_173's grid_metatile.tsv to start it over)")
        return
    # blocks: all of Vale's, so the editor's palette has everything
    art_mt = project.load_metatiles(art)
    mt = tablemod.parse(art_mt.to_text())
    tablemod.save(mt, os.path.join(folder, "metatiles.tsv"))
    # Vale's commonest walkable ground block, a path block, and the block its
    # upper layers are mostly filled with (drawn as nothing)
    ab = project.resolved_blocks(art)
    ac = project.load_grid(art, "collision").cells
    ground, upper = collections.Counter(), collections.Counter()
    for li, counter in ((0, ground), (1, upper)):
        lx, ly = project.layer_origin(art, li)
        for y in range(art.size[1]):
            for x in range(art.size[0]):
                if li == 1 or ac[ly + y][lx + x] == 0:
                    counter[ab[ly + y][lx + x] & 0xFFF] += 1
    grass = ground.most_common(1)[0][0]
    empty = upper.most_common(1)[0][0]
    # The way-back pad: of the 15 commonest walkable blocks, the one whose
    # average colour is furthest from the grass, so it stands out.
    atlas = project.metatile_atlas(art, art.char_base[0])

    def mean(b):
        tile = atlas.crop(((b % 32) * 16, (b // 32) * 16, (b % 32) * 16 + 16, (b // 32) * 16 + 16))
        px = [q for q in tile.getdata() if q[3]]
        return [sum(c[i] for c in px) / max(len(px), 1) for i in range(3)]

    g = mean(grass)
    path = max((b for b, _ in ground.most_common(15) if b != grass),
               key=lambda b: sum((a - c) ** 2 for a, c in zip(mean(b), g)))
    # planes: 32x32 windows for L0 (cells 0..31), L1 (32..63), L2 (64..95)
    project2 = Project(root)
    sb = project2.maps[SANDBOX_MAP]
    from gsmap import grid as gridmod
    planes = {p: gridmod.load(sb.plane_path(p)) for p in ("metatile", "collision", "shape")}
    blocks = [[0] * 128 for _ in range(128)]
    col = [[0] * 128 for _ in range(128)]
    for y in range(32):
        for x in range(32):
            blocks[y][x] = grass
            blocks[y][32 + x] = empty
            blocks[y][64 + x] = empty
            if x in (0, 31) or y in (0, 31):
                col[y][x] = 0xFF
    bx, by = 12, 14  # the way back, two cells below the arrival point (12, 12)
    blocks[by][bx] = path
    col[by][bx] = SANDBOX_RETURN_CODE
    planes["metatile"].cells = project2.encode_placeholders(blocks)[0]
    planes["collision"].cells = col
    planes["shape"].cells = [[0] * 128 for _ in range(128)]
    for p, g in planes.items():
        gridmod.save(g, sb.plane_path(p))
    # the editor's name for it
    names_path = os.path.join(root, "games/tbs/src/mod/names.json")
    names = json.load(open(names_path)) if os.path.exists(names_path) else {}
    names.setdefault("scenes", {})[str(SANDBOX_SCENE)] = "Debug · Sandbox"
    names["scenes"][str(HUB_SCENE)] = "Debug · Hub"
    with open(names_path, "w", encoding="utf-8") as f:
        json.dump(names, f, indent=1)
        f.write("\n")
    print(f"sandbox: grass {grass}, path {path}, empty upper {empty}, {len(mt.rows)} blocks")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.expanduser("~/gs_project/alchemy"))
    args = ap.parse_args()
    project, scenes, names = Project(args.root), Scenes(args.root), Names(args.root)
    hub, art = project.maps[HUB_MAP], project.maps[ART_MAP]

    # ---- destinations: every scene, at its lowest entrance -------------------
    dests = []
    for sc in scenes.scenes:
        if sc["id"] in SKIP:
            continue
        try:
            o = scenes.overlay(sc["overlay"])
            nums = sorted({r["entrance"] for n, t in o.tables.items()
                           if t["kind"] == "entrances" and t["editable"]
                           for r in o.rows(n) if r["entrance"] >= 0})
        except FileNotFoundError:
            nums = []
        place = names.places.get(sc["id"], {})
        dests.append({
            "scene": sc["id"], "label": names.scene_label(sc["id"]),
            "entrance": nums[0] if nums else 0,  # the engine falls back to row 0
            "message": place.get("area_message"),
        })
    if len(dests) > 239:
        raise SystemExit("more destinations than trigger codes")

    # The sandbox pad starts a new row below the others.
    dests.append({"scene": SANDBOX_SCENE, "label": "Debug · Sandbox", "entrance": 0,
                  "message": None, "sandbox": True})

    # ---- pads: odd cells of the 32x32 room, row by row -------------------------
    w, h = hub.size
    slots = [(x, y) for y in range(1, h, 2) for x in range(1, w, 2)]
    if len(dests) > len(slots):
        raise SystemExit("room too small")
    for i, d in enumerate(dests):
        d["code"] = d["kind"] = i + 1
        d["cell"] = slots[i]
    last_row = max(d["cell"][1] for d in dests[:-1])
    dests[-1]["code"] = dests[-1]["kind"] = SANDBOX_CODE
    dests[-1]["cell"] = (1, last_row + 2)
    make_sandbox(project, args.root)

    # ---- tile set: layered.tsv row 178 takes map 009's resources ---------------
    lpath = os.path.join(project.tbs, "field/layered.tsv")
    lt = tablemod.load(lpath)
    art_row = art.resources["row"]
    for c in range(1, 6):  # keep column 0, the hub's own map header
        lt.set(HUB_ROW, c, lt.rows[art_row][c])
    tablemod.save(lt, lpath)

    # ---- blocks: floor and pad, copied from map 009 ----------------------------
    art_blocks = project.resolved_blocks(art)
    art_col = project.load_grid(art, "collision").cells
    floor_counts, other = collections.Counter(), collections.Counter()
    lx, ly = project.layer_origin(art, 0)
    for y in range(art.size[1]):
        for x in range(art.size[0]):
            b = art_blocks[ly + y][lx + x] & 0xFFF
            (floor_counts if art_col[ly + y][lx + x] in (0, 0xF0) else other)[b] += 1
    floor_block = floor_counts.most_common(1)[0][0]
    pad_block = next(b for b, _ in floor_counts.most_common() if b != floor_block)
    art_mt = project.load_metatiles(art)
    mpath = hub.source("METATILES", "metatiles.tsv")
    mt = tablemod.load(mpath)
    mt.rows, mt._spellings = [], []
    for b in (floor_block, pad_block):
        mt.append(art_mt.rows[b])
    tablemod.save(mt, mpath)

    # ---- paint pads and codes (the editor's save path) -------------------------
    l0 = hub.layers[0]
    gx0, gy0 = l0[0] // 2 + hub.bounds[0] // 2, l0[1] // 2 + hub.bounds[1] // 2
    edits = []
    for d in dests:
        x, y = d["cell"]
        gx, gy = (gx0 + x) % 128, (gy0 + y) % 128
        edits += [{"plane": "block", "x": gx, "y": gy, "value": 1},
                  {"plane": "collision", "x": gx, "y": gy, "value": d["code"]}]
    res = project.apply_edits(hub, edits)

    # ---- one "Pad N: warp to <place>" message per pad (English catalog) -------
    back = {"code": SANDBOX_RETURN_CODE, "label": "the debug hub"}
    msgs = write_messages(os.path.join(args.root, "games/tbs/text/en.po"), dests + [back])
    for d, msg in zip(dests, msgs):
        d["message"] = msg
    back["message"] = msgs[-1]

    # ---- scene tables: exit + look-at events, exits ------------------------------
    o = scenes.overlay(HUB_OVERLAY)
    events = [r for r in o.rows("gTestRooms_Events") if r["control"] != 0xFFFFFFFF]
    for d in dests:
        events.append({"control": EVENT_EXIT_CONTROL, "trigger": d["code"],
                       "condition": -1, "value": d["kind"]})
        if d["message"] is not None:
            events.append({"control": SEARCH_MESSAGE_CONTROL, "trigger": d["code"],
                           "condition": -1, "value": FIND_MESSAGE | d["message"]})
    events += [{"control": EVENT_EXIT_CONTROL, "trigger": SANDBOX_RETURN_CODE, "condition": -1,
                "value": SANDBOX_RETURN_CODE},
               {"control": SEARCH_MESSAGE_CONTROL, "trigger": SANDBOX_RETURN_CODE, "condition": -1,
                "value": FIND_MESSAGE | back["message"]}]
    events.append({"control": 0xFFFFFFFF, "trigger": 0, "condition": 0, "value": 0})
    exits = copy.deepcopy(o.rows("gTestRooms_Exits"))
    seg = next(s for s in exits if s.get("scene") == HUB_SCENE)
    seg["exits"] = [{"kind": d["kind"], "scene": d["scene"], "entrance": d["entrance"],
                     "flag": None, "extra": 0} for d in dests]
    sseg = next(s for s in exits if s.get("scene") == SANDBOX_SCENE)
    sseg["exits"] = [{"kind": SANDBOX_RETURN_CODE, "scene": HUB_SCENE, "entrance": 0,
                      "flag": None, "extra": 0}]
    validate_rows("events", events)
    validate_rows("exits", exits)
    ov = Overrides(args.root)
    ov.set(HUB_OVERLAY, "gTestRooms_Events", "events", events)
    ov.set(HUB_OVERLAY, "gTestRooms_Exits", "exits", exits)
    ov.save()
    summary = generate(args.root, scenes, ov)

    # ---- labelled picture of the hub --------------------------------------------
    project = Project(args.root)  # re-read the edited files
    img = project.render(project.maps[HUB_MAP]).convert("RGB")
    img = img.resize((img.width * 3, img.height * 3), Image.NEAREST)
    draw = ImageDraw.Draw(img)
    for d in dests:
        x, y = d["cell"]
        draw.text((x * 48 + 2, y * 48 + 2), str(d["code"]), fill=(255, 255, 0))
        draw.text((x * 48 + 2, y * 48 + 14), d["label"].split(" · ")[0][:9], fill=(255, 255, 255))
    ex, ez = 12, 12  # entrance 0 at (192, 192) px
    draw.rectangle([ex * 48, ez * 48, ex * 48 + 47, ez * 48 + 47], outline=(0, 255, 0), width=3)
    out = os.path.join(HERE, "..", "docs")
    img.save(os.path.join(out, "debug-hub.png"))
    with open(os.path.join(out, "debug-hub.json"), "w", encoding="utf-8") as f:
        json.dump([{k: d[k] for k in ("code", "cell", "scene", "label", "entrance")} for d in dests], f, indent=1)
    print(f"{len(dests)} pads; floor block {floor_block}, pad block {pad_block} from map {ART_MAP}")
    print("saved", [os.path.relpath(p, args.root) for p in res["saved"]], res["warnings"])
    print("mod", summary)


if __name__ == "__main__":
    main()
