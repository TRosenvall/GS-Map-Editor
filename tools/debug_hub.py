"""NOT PORTED: written for the alchemy layout before map.txt; kept as a record of
how the hub and sandbox were made. tools/port_mod.py carried their result over.

Turn the first Djinn test room (scene 191, map 172) into a hub with a pad
to every place in the game.

Everything goes through gs-mapedit's own engine, the way the editor saves:
  - field/layered.tsv row 178 (only scene 191 uses it): Sol Sanctum's palette
    and tile sheets, copied from map 009's row, so the room has visible art.
  - map_172 metatiles: a floor block and a pad block copied from map 009.
  - map_172 planes (Project.apply_edits): pads on odd cells, each with its
    own collision code 1..N.
  - overlay 0x3cc events/exits (Overrides + generate): per pad an EVENT_EXIT
    (step on it) and a search event showing the place's area name (face it,
    press A); scene 191's exits send kind i to (scene, lowest entrance).

Run from gs-mapedit:  python3 tools/debug_hub.py [--root ~/gs_project/alchemy]
It writes docs/debug-hub.png (labelled pads) and docs/debug-hub.json.
"""

